export type PixelIconName = keyof typeof GRIDS

export default function PixelIcon({
  name,
  size = 20,
  color = 'currentColor',
  className = '',
}: {
  name: string
  size?: number
  color?: string
  className?: string
}) {
  const grid = GRIDS[name] ?? GRIDS.newspaper
  const cell = size / 8
  const r = cell * 0.36

  return (
    <svg width={size} height={size} viewBox={`0 0 ${size} ${size}`} className={className} aria-hidden>
      {grid.map((row, y) =>
        row.split('').map((ch, x) =>
          ch === '#' ? (
            <circle
              key={`${x}-${y}`}
              cx={x * cell + cell / 2}
              cy={y * cell + cell / 2}
              r={r}
              fill={color}
            />
          ) : null
        )
      )}
    </svg>
  )
}
